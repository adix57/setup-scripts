#!/usr/bin/env bash
set -euo pipefail

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
NC='\033[0m'

info()  { echo -e "${CYAN}[INFO]${NC}  $*"; }
ok()    { echo -e "${GREEN}[OK]${NC}    $*"; }
warn()  { echo -e "${YELLOW}[WARN]${NC}  $*"; }
err()   { echo -e "${RED}[ERROR]${NC} $*" >&2; }

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="$SCRIPT_DIR/env"

detect_distro() {
    if [ -f /etc/os-release ]; then
        . /etc/os-release
        case "$ID" in
            arch|manjaro|endeavouros|omarchy) echo "arch" ;;
            debian|ubuntu|linuxmint|pop|raspbian|kali) echo "debian" ;;
            fedora) echo "fedora" ;;
            *) err "Unsupported distro: $ID"; exit 1 ;;
        esac
    else
        err "Cannot detect distro (missing /etc/os-release)"
        exit 1
    fi
}

detect_shells() {
    local shells=()
    [ -n "${BASH_VERSION:-}" ] && shells+=("bash")
    [ -n "${ZSH_VERSION:-}" ]  && shells+=("zsh")

    local login_shell
    login_shell=$(basename "${SHELL:-/bin/bash}")
    case "$login_shell" in
        bash|zsh|fish) shells+=("$login_shell") ;;
    esac

    local result
    result=$(printf '%s\n' "${shells[@]}" | sort -u | tr '\n' ',')
    echo "${result%,}"
}

install_deps() {
    local distro=$1
    info "Installing dependencies for $distro..."

    case "$distro" in
        arch)
            sudo pacman -Sy --needed --noconfirm base-devel curl git
            ;;
        debian)
            sudo apt-get update -y
            sudo apt-get install -y build-essential curl git
            ;;
        fedora)
            sudo dnf install -y gcc make curl git
            ;;
    esac
    ok "Dependencies installed"
}

ensure_fzf() {
    command -v fzf &>/dev/null && return

    warn "fzf not found. Installing..."
    local distro
    distro=$(detect_distro)

    case "$distro" in
        arch) sudo pacman -S --needed --noconfirm fzf ;;
        debian) sudo apt-get install -y fzf ;;
        fedora) sudo dnf install -y fzf ;;
    esac
    ok "fzf installed"
}

load_env() {
    if [ -f "$ENV_FILE" ]; then
        # shellcheck disable=SC1090
        source "$ENV_FILE"
        return
    fi

    local distro shells
    distro=$(detect_distro)
    shells=$(detect_shells)

    cat > "$ENV_FILE" << EOF
# Auto-generated by setup.sh — do not edit
DISTRO=$distro
SHELLS=$shells
EOF

    # shellcheck disable=SC1090
    source "$ENV_FILE"
}

regen_env() {
    local distro shells
    distro=$(detect_distro)
    shells=$(detect_shells)

    cat > "$ENV_FILE" << EOF
# Auto-generated by setup.sh — do not edit
DISTRO=$distro
SHELLS=$shells
EOF

    ok "Regenerated $ENV_FILE"
}

list_scripts() {
    find "$SCRIPT_DIR/scripts" -maxdepth 1 -name 'setup-*.sh' -type f | sort
}

main() {
    load_env

    local items=()
    while IFS= read -r s; do
        items+=("$(basename "$s" .sh | sed 's/^setup-//')")
    done < <(list_scripts)

    if [ ${#items[@]} -eq 0 ]; then
        err "No setup scripts found in $SCRIPT_DIR/scripts/"
        exit 1
    fi

    local selected
    selected=$(printf '%s\n' "${items[@]}" | fzf --multi --prompt="Pick tools to install > " --height=40% --reverse) || true

    if [ -z "$selected" ]; then
        exit 0
    fi

    export DISTRO="$DISTRO"
    export SHELLS="$SHELLS"

    echo "$selected" | while IFS= read -r name; do
        local target="$SCRIPT_DIR/scripts/setup-${name}.sh"
        if [ -f "$target" ]; then
            bash "$target"
        else
            warn "Script not found: $target"
        fi
    done

    echo ""
    ok "Done!"
    echo ""
}

case "${1:-}" in
    --help|-h)
        echo ""
        echo "Usage: ./setup.sh [option]"
        echo ""
        echo "Options:"
        echo "  (none)     Launch interactive fzf menu"
        echo "  --regen    Regenerate the env file"
        echo "  --help     Show this help"
        echo ""
        ;;
    --regen)
        regen_env
        ;;
    *)
        main
        ;;
esac
